import { chromium } from '@playwright/test';
import { readFileSync } from 'node:fs';
const [,, out, street, plate] = process.argv;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on('console', (m) => { if (m.type() === 'error') console.log('console error:', m.text().slice(0, 200)); });
await p.goto('http://localhost:5181');
await p.getByTestId('file-input').setInputFiles({ name: 'street.jpg', mimeType: 'image/jpeg', buffer: readFileSync(street) });
await p.getByTestId('workspace').waitFor();
await p.getByTestId('tools-rail').getByRole('button', { name: 'Protect' }).click();
const t0 = Date.now();
await p.getByText('Protection model ready.').waitFor({ timeout: 120000 });
console.log('model ready in', Date.now() - t0, 'ms');
await p.getByRole('button', { name: 'Protect photo' }).click();
await p.getByText('Protected copy ready').waitFor({ timeout: 240000 });
console.log('protect:', (await p.getByTestId('protect-panel').innerText()).replace(/\s+/g, ' ').slice(0, 260));
await p.screenshot({ path: `${out}/protect-done.png` });
await p.getByTestId('file-input').first().setInputFiles({ name: 'plate.jpg', mimeType: 'image/jpeg', buffer: readFileSync(plate) }).catch(() => {});
await p.waitForTimeout(1500);
await p.getByTestId('tools-rail').getByRole('button', { name: 'Clean' }).click();
await p.waitForFunction(() => /Removed|removed|Save|saved|nothing|No private/i.test(document.querySelector('[data-testid="clean-panel"]')?.textContent ?? ''), null, { timeout: 180000 }).catch(() => console.log('clean: timed out'));
await p.waitForTimeout(2000);
console.log('clean:', (await p.getByTestId('clean-panel').innerText()).replace(/\s+/g, ' ').slice(0, 300));
await p.screenshot({ path: `${out}/clean-auto.png` });
await b.close();
