import { chromium } from '@playwright/test';
const base = process.env.VEIL_URL ?? 'http://localhost:5191/';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(base + '#/trace', { waitUntil: 'networkidle' });
await page.locator('input[type=file]').setInputFiles('public/demo/source/selfie-1.jpg');
await page.waitForSelector('.vault-list li', { timeout: 90000 });
console.log('enrolled faces:', await page.locator('.vault-list li').count());
const t0 = Date.now();
await page.getByRole('button', { name: 'demo leaks page' }).click();
await page.waitForFunction(() => /pictures show you|matches your face|Could not scan/.test(document.querySelector('.results-head')?.textContent ?? ''), null, { timeout: 180000 });
console.log('scan ms', Date.now() - t0, '|', await page.locator('.results-head').innerText());
console.log('hits:', await page.locator('.hits li .hit-label').allInnerTexts());
await page.screenshot({ path: (process.env.VEIL_OUT ?? '../scratch-eval') + '/e2e-trace.png' });
await page.goto(base + '#/tickets', { waitUntil: 'networkidle' });
console.log('tickets:', await page.locator('.ticket-list li').count());
await page.locator('.ticket-list li a').first().click();
await page.waitForTimeout(4000);
await page.screenshot({ path: (process.env.VEIL_OUT ?? '../scratch-eval') + '/e2e-ticket.png', fullPage: true });
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
await browser.close();
